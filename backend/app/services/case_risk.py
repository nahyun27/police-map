"""사건 공론화 글의 개인정보·실명 노출 위험 자동 탐지.

2026-10 결정: 사전 검토 없이 즉시 공개하되, 여기서 위험이 탐지된 글만 공개를 보류(held)하고
관리자가 확인한다. 정규식 기반 휴리스틱이라 놓치는 것도, 과하게 잡는 것도 있다 — 판단은 항상
관리자가 하고, 이 모듈은 "확인이 필요한 글"을 골라내는 보조 역할만 한다. 과하게 잡아서 보류된
글은 관리자가 승인하면 그대로 공개된다.

실명 금지만으로는 충분하지 않다는 점(경찰서 + 시점만으로 담당자가 특정될 수 있음)은 운영원칙
안내로 다루고, 여기서는 기계적으로 잡을 수 있는 것만 잡는다."""
import re

_PATTERNS: list[tuple[str, re.Pattern]] = [
    ("전화번호", re.compile(r"01[016789][\s.-]?\d{3,4}[\s.-]?\d{4}|0\d{1,2}-\d{3,4}-\d{4}")),
    ("이메일", re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")),
    ("주민등록번호", re.compile(r"\d{6}\s?-\s?[1-4]\d{6}")),
    ("사건번호", re.compile(r"\d{2,4}\s*-?\s*(형제|고합|고단|고정|형사|진정|내사)\s*-?\s*\d{2,}")),
]

# "김철수 경위", "박 수사관" 처럼 성씨로 시작하는 이름 + 계급·직함. 성씨 목록으로 시작하는 2~4자만 본다.
_SURNAMES = "김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구민나진지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예봉경"
_RANKS = "순경|경장|경사|경위|경감|경정|총경|수사관|형사|팀장|수사팀장|조사관"
_NAME_RANK = re.compile(rf"(?<![가-힣])([{_SURNAMES}][가-힣]{{0,3}})\s?({_RANKS})")
# 성씨 글자로 시작하지만 사람 이름이 아닌 흔한 말 — "조사 경위", "진술 경위" 같은 오탐을 막는다.
_NOT_NAMES = {
    "조사", "진술", "사건", "수사", "고소", "처리", "신고", "접수", "발생", "이송", "진정", "민원", "담당", "해당",
    "당시", "이후", "최초", "사고", "피해", "체포", "구속", "송치", "종결", "경찰", "정확한", "구체적", "전체",
    "자세한", "관련", "강력", "지능", "경제", "여성", "청소년", "교통", "사이버", "형사", "민사", "이", "그", "저",
    "한", "전", "현", "남", "여", "주", "원",
}


def detect(*texts: str | None) -> list[str]:
    """위험 항목 이름 목록(중복 없음, 발견 순)."""
    text = "\n".join(t for t in texts if t)
    found: list[str] = []
    for label, pat in _PATTERNS:
        if pat.search(text) and label not in found:
            found.append(label)
    for m in _NAME_RANK.finditer(text):
        name = m.group(1)
        # "민원실 경위", "수사과 형사"처럼 기관·부서 이름(실·과·서·대·소·팀·청·부로 끝나는 3자 이상)은 이름이 아니다.
        if name not in _NOT_NAMES and not (len(name) >= 3 and name[-1] in "실과서대소팀청부"):
            found.append("실명+계급 추정 표현")
            break
    return found
